const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (ch) => (fn) => ipcRenderer.on(ch, (_e, d) => fn(d));
contextBridge.exposeInMainWorld('multi', {
  onAccounts: on('accounts'),
  onSessions: on('sessions'),
  onView: on('view'),
  onAppend: on('append'),
  onPrepend: on('prepend'),
  onLive: on('live'),
  onPrefs: on('chat-prefs'),
  onAsk: on('ask'),
  onSelect: on('select'),
  onCollapsed: on('collapsed'),
  onCommands: on('commands'),
  onUsageDone: on('usage-done'),
  refreshUsage: () => ipcRenderer.invoke('refresh-usage'),
  commands: () => ipcRenderer.invoke('commands'),
  onOrg: on('org'),
  organise: (op) => ipcRenderer.invoke('organise', op),
  chatMenu: (key) => ipcRenderer.invoke('chat-menu', key),
  folderMenu: (id) => ipcRenderer.invoke('folder-menu', id),
  markAllRead: () => ipcRenderer.invoke('mark-all-read'),
  deleteChat: (key) => ipcRenderer.invoke('delete-chat', key),
  voiceType: () => ipcRenderer.invoke('voice-type'),
  speakLast: (key) => ipcRenderer.invoke('speak-last', key),
  stopSpeaking: () => ipcRenderer.invoke('stop-speaking'),
  exportChat: (key) => ipcRenderer.invoke('export-chat', key),
  init: () => ipcRenderer.invoke('init'),
  open: (key) => ipcRenderer.invoke('open', key),
  more: () => ipcRenderer.invoke('more'),
  setPrefs: (key, patch) => ipcRenderer.invoke('set-prefs', key, patch),
  setCollapsed: (c) => ipcRenderer.invoke('set-collapsed', c),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  reveal: (key) => ipcRenderer.invoke('reveal', key),
  send: (key, text, files) => ipcRenderer.invoke('send', key, text, files),
  saveAttachment: (name, bytes) => ipcRenderer.invoke('save-attachment', name, bytes),
  pathOf: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch { return ''; } },
  stop: (key) => ipcRenderer.invoke('stop', key),
  onQueue: on('queue'),
  unqueue: (key, id) => ipcRenderer.invoke('unqueue', key, id),
  sendNow: (key, text, files) => ipcRenderer.invoke('send-now', key, text, files),
  queueSendNow: (key, id) => ipcRenderer.invoke('queue-send-now', key, id),
  answer: (key, id, reply) => ipcRenderer.invoke('answer', key, id, reply),
  onUpdate: on('update'),
  restart: (whenIdle) => ipcRenderer.invoke('restart', whenIdle),
  openFile: (p) => ipcRenderer.invoke('open-file', p),
  revealFile: (p) => ipcRenderer.invoke('reveal-file', p),
  addAccount: (o) => ipcRenderer.invoke('add-account', o),
  accountMenu: (id) => ipcRenderer.invoke('account-menu', id),
  renameAccount: (id, name) => ipcRenderer.invoke('rename-account', id, name),
  openExternal: (u) => ipcRenderer.invoke('open-external', u),
});
